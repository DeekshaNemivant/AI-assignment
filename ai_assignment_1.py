"""**Iterative Deepening**"""

def dls(graph, node, goal, limit, path=None):
    if path is None:
        path = [node]

    if node == goal:
        return path

    if limit == 0:
        return None

    for next in graph[node]:
        if next not in path:
            result = dls(graph, next, goal, limit - 1, path + [next])
            if result is not None:
                return result
    return None

def iddfs(graph, start, goal, max_depth=10):
    for depth in range(max_depth + 1):
        print("Trying depth limit =", depth)
        result = dls(graph, start, goal, depth)
        if result is not None:
            return result
    return None

path = iddfs(graph, 'A', 'F')
