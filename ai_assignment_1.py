"""**BFS**"""

from collections import deque
def bfs(graph,start):
  visited=set()
  queue=deque([start])
  visited.add(start)

  while queue:
    node=queue.popleft()
    print(node,end=" ")

    for next in graph[node]:
      if next not in visited:
        visited.add(next)
        queue.append(next)
print("BFS")
bfs(graph,'A')

"""**Uniform cost Search**"""

import heapq

graph_ucs={
    'A':[('B',1),('C',4)],
    'B':[('D',3),('E',1)],
    'C':[('F',2)],
    'D':[],
    'E':[('F',5)],
    'F':[]

}

def ucs(graph,start,goal):
  visited=set()
  queue=[(0,start,[start])] #(cost so far,node,path)
  while queue:
    cost,node,path=heapq.heappop(queue)
    if node in visited:
      continue
    visited.add(node)
    if node==goal:
      print("Path:","->".join(path))
      print("Total Cost:",cost)
      return
    for next,weight in graph_ucs[node]:
        if next not in visited:
          heapq.heappush(queue,(cost+weight,next,path+[next]))
  print("No path found")
print("UCS")
ucs(graph_ucs,'A','F')

