def greedy_bfs(start,goal):
  open_list = [(h[start], start, [start])]  #(h value,node,path so far)-nodes that are need to explore
  visited=set()
  while open_list:
    _, node ,path =heapq.heappop(open_list) #heappop removes the entry with the lowest h value
    if node==goal:
      return path
    if node in visited:
      continue
    visited.add(node)
    for neighbour in graph[node]:
      if neighbour not in visited:
        heapq.heappush(open_list,(h[neighbour],neighbour,path+[neighbour]))
  return None
