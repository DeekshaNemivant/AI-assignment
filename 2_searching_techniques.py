"""#(iv)  A* algorithm"""

import heapq
# Heuristic h(n): estimated cost from each node to goal G
h = {'S': 5, 'A': 4, 'B': 3, 'C': 2, 'D': 6, 'G': 0}

def a_star(start, goal):
    open_list = [(h[start], 0, start, [start])]   # (f, g, node, path)
    visited = set()
    while open_list:
        f, g, node, path = heapq.heappop(open_list)   # lowest f = g + h first
        if node == goal:
            return g, path
        if node in visited:
            continue
        visited.add(node)
        for neighbour, weight in graph[node].items():
            if neighbour not in visited:
                new_g = g + weight
                heapq.heappush(open_list, (new_g + h[neighbour], new_g, neighbour, path + [neighbour]))
    return None, None

cost, path = a_star('S', 'G')
if path:
    print("Path:", "->".join(path), "| Total cost:", cost)
else:
    print("No path")

"""#(v)Beam search

"""

def beam_search(start, goal, k=2):
    beam = [(h[start], start, [start])]
    while beam:
        candidates = []
        for _, node, path in beam:
            if node == goal:
                return path
            for nb in graph[node]:
                if nb not in path:
                    candidates.append((h[nb], nb, path + [nb]))
        beam = sorted(candidates)[:k]      # keep only the k best
    return None

path = beam_search("S", "G", k=2)
cost = sum(graph[a][b] for a, b in zip(path, path[1:]))
print("Path:", "->".join(path), "| Total cost:", cost)





