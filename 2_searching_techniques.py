def rbfs(node, g, path, f_limit):
    if node == "G":
        return path, g
    succ = []
    for nb, w in graph[node].items():
        if nb not in path:
            ng = g + w
            succ.append([max(ng + h[nb], g + h[node]), ng, nb])
    if not succ:
        return None, float("inf")
    while True:
        succ.sort()
        best = succ[0]
        if best[0] > f_limit:
            return None, best[0]
        alt = succ[1][0] if len(succ) > 1 else float("inf")
        result, val = rbfs(best[2], best[1], path + [best[2]], min(f_limit, alt))
        if result is not None:
            return result, val
        best[0] = val                      # back up the best f found

path, cost = rbfs("S", 0, ["S"], float("inf"))
print("Path:", "->".join(path), "Total cost:", cost)



"""#(vii) IDA*"""

def ida_star(start, goal):
    path = [start]

    def search(g, threshold):
        node = path[-1]
        f = g + h[node]
        if f > threshold:
            return f, False
        if node == goal:
            return g, True
        minimum = float("inf")
        for nb, w in graph[node].items():
            if nb not in path:
                path.append(nb)
                t, found = search(g + w, threshold)
                if found:
                    return t, True
                minimum = min(minimum, t)
                path.pop()
        return minimum, False

    threshold = h[start]
    while True:
        t, found = search(0, threshold)
        if found:
            return t, path
        if t == float("inf"):
            return None, None
        threshold = t                      # raise the f-limit

cost, path = ida_star("S", "G")
print("Path:", "->".join(path), "Total cost:", cost)



"""#(viii) Weighted A*"""

def weighted_a_star(start, goal, w=2):
    open_list = [(w * h[start], 0, start, [start])]   # (f, g, node, path)
    visited = set()
    while open_list:
        f, g, node, path = heapq.heappop(open_list)
        if node == goal:
            return g, path
        if node in visited:
            continue
        visited.add(node)
        for nb, cost in graph[node].items():
            if nb not in visited:
                ng = g + cost
                heapq.heappush(open_list, (ng + w * h[nb], ng, nb, path + [nb]))
    return None, None

cost, path = weighted_a_star("S", "G", w=2)
print("Path:", "->".join(path), "| Total cost:", cost)